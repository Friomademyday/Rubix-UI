import React, { useState, useEffect, useRef } from 'react';
import * as THREE from 'three';

const RubixCubeCanvas = ({ size = 24, isSpinning = true }) => {
  const mountRef = useRef(null);
  const isSpinningRef = useRef(isSpinning);

  useEffect(() => {
    isSpinningRef.current = isSpinning;
  }, [isSpinning]);

  useEffect(() => {
    const container = mountRef.current;
    if (!container) return;

    const scene = new THREE.Scene();
    const camera = new THREE.PerspectiveCamera(45, 1, 0.1, 100);
    camera.position.set(3, 3, 4);
    camera.lookAt(0, 0, 0);

    const renderer = new THREE.WebGLRenderer({ alpha: true, antialias: true });
    renderer.setSize(size, size);
    container.appendChild(renderer.domElement);

    const ambientLight = new THREE.AmbientLight(0xffffff, 0.8);
    scene.add(ambientLight);

    const dirLight = new THREE.DirectionalLight(0xffffff, 0.6);
    dirLight.position.set(5, 5, 5);
    scene.add(dirLight);

    const rubixGroup = new THREE.Group();
    scene.add(rubixGroup);

    const blockGeometry = new THREE.BoxGeometry(0.58, 0.58, 0.58);
    const materials = [
      new THREE.MeshLambertMaterial({ color: 0xb71c1c }), // Right (Red)
      new THREE.MeshLambertMaterial({ color: 0xff6f00 }), // Left (Orange)
      new THREE.MeshLambertMaterial({ color: 0xffeb3b }), // Top (Yellow)
      new THREE.MeshLambertMaterial({ color: 0xffffff }), // Bottom (White)
      new THREE.MeshLambertMaterial({ color: 0x1b5e20 }), // Front (Green)
      new THREE.MeshLambertMaterial({ color: 0x0d47a1 })  // Back (Blue)
    ];

    const offset = 0.62;
    for (let x = -1; x <= 1; x++) {
      for (let y = -1; y <= 1; y++) {
        for (let z = -1; z <= 1; z++) {
          const block = new THREE.Mesh(blockGeometry, materials);
          block.position.set(x * offset, y * offset, z * offset);
          rubixGroup.add(block);
        }
      }
    }

    let animationFrameId;
    const animate = () => {
      animationFrameId = requestAnimationFrame(animate);
      if (isSpinningRef.current) {
        rubixGroup.rotation.x += 0.01;
        rubixGroup.rotation.y += 0.015;
      }
      renderer.render(scene, camera);
    };
    animate();

    return () => {
      cancelAnimationFrame(animationFrameId);
      if (container.contains(renderer.domElement)) {
        container.removeChild(renderer.domElement);
      }
      renderer.dispose();
    };
  }, [size]);

  return <div ref={mountRef} style={{ width: size, height: size, display: 'inline-block' }} />;
};

export default function App() {
  const [messages, setMessages] = useState([]);
  const [input, setInput] = useState('');
  const [isThinking, setIsThinking] = useState(false);
  const [selectedModel, setSelectedModel] = useState('Rubix 1.2');
  const [isSidebarOpen, setIsSidebarOpen] = useState(false);
  const [isMenuOpen, setIsMenuOpen] = useState(false);
  const chatEndRef = useRef(null);

  const historyItems = [
    'Welcome to Rubix',
    'Exploring an idea',
    'Project discussion'
  ];

  useEffect(() => {
    chatEndRef.current?.scrollIntoView({ behavior: 'smooth' });
  }, [messages, isThinking]);

  const handleSend = () => {
    if (!input.trim() || isThinking) return;

    const userMsg = { id: Date.now(), sender: 'user', text: input.trim() };
    setMessages((prev) => [...prev, userMsg]);
    setInput('');
    setIsThinking(true);

    setTimeout(() => {
      const aiMsg = {
        id: Date.now() + 1,
        sender: 'ai',
        text: `This is a response generated by ${selectedModel}.`
      };
      setMessages((prev) => [...prev, aiMsg]);
      setIsThinking(false);
    }, 2500);
  };

  const handleNewChat = () => {
    setMessages([]);
    setInput('');
    setIsThinking(false);
  };

  return (
    <div className="app-container">
      <header className="header">
        <div className="header-left">
          <button className="icon-btn" onClick={() => setIsSidebarOpen(true)}>
            <RubixCubeCanvas size={24} isSpinning={false} />
          </button>
          <button className="new-chat-btn" onClick={handleNewChat}>
            + New Chat
          </button>
        </div>

        <select
          className="model-selector"
          value={selectedModel}
          onChange={(e) => setSelectedModel(e.target.value)}
        >
          <option value="Rubix 1.2">Rubix 1.2</option>
          <option value="Rubix Deep Thinking">Rubix Deep Thinking</option>
          <option value="Rubix Pro">Rubix Pro</option>
        </select>
      </header>

      {isSidebarOpen && (
        <>
          <div className="backdrop" onClick={() => setIsSidebarOpen(false)} />
          <aside className="sidebar-drawer">
            <div className="sidebar-header">
              <h3>History</h3>
              <button className="close-btn" onClick={() => setIsSidebarOpen(false)}>
                ×
              </button>
            </div>
            <ul className="history-list">
              {historyItems.map((item, index) => (
                <li key={index} className="history-item">
                  {item}
                </li>
              ))}
            </ul>
          </aside>
        </>
      )}

      <main className="chat-container">
        {messages.length === 0 ? (
          <div className="welcome-screen">
            <RubixCubeCanvas size={64} isSpinning={true} />
            <h2>Talk to Rubix</h2>
            <p>Select a model and start a conversation.</p>
          </div>
        ) : (
          <div className="message-list">
            {messages.map((msg) => (
              <div
                key={msg.id}
                className={`message-row ${msg.sender === 'user' ? 'user' : 'ai'}`}
              >
                {msg.sender === 'ai' && (
                  <div className="msg-icon">
                    <RubixCubeCanvas size={18} isSpinning={false} />
                  </div>
                )}
                <div className="message-bubble">{msg.text}</div>
              </div>
            ))}

            {isThinking && (
              <div className="message-row ai">
                <div className="msg-icon">
                  <RubixCubeCanvas size={18} isSpinning={isThinking} />
                </div>
                <div className="message-bubble thinking-text">
                  Rubixing...
                </div>
              </div>
            )}
            <div ref={chatEndRef} />
          </div>
        )}
      </main>

      <footer className="composer-container">
        <div className="composer-box">
          <div className="menu-wrapper">
            <button className="icon-btn" onClick={() => setIsMenuOpen(!isMenuOpen)}>
              +
            </button>
            {isMenuOpen && (
              <div className="popover-menu">
                <button onClick={() => setIsMenuOpen(false)}>Upload file</button>
                <button onClick={() => setIsMenuOpen(false)}>Add image</button>
                <button onClick={() => setIsMenuOpen(false)}>Add context</button>
              </div>
            )}
          </div>

          <textarea
            className="chat-textarea"
            rows="1"
            placeholder="Ask Rubix..."
            value={input}
            onChange={(e) => setInput(e.target.value)}
            onKeyDown={(e) => {
              if (e.key === 'Enter' && !e.shiftKey) {
                e.preventDefault();
                handleSend();
              }
            }}
          />

          <button className="icon-btn">🎤</button>
          <button
            className="send-btn"
            disabled={!input.trim() || isThinking}
            onClick={handleSend}
          >
            Send
          </button>
        </div>
        <div className="disclaimer">
          Rubix can make mistakes. Check important information.
        </div>
      </footer>
    </div>
  );
  }
